#!/usr/bin/env node
// Telegrade scaffolder. Generates the thin Next.js route files that re-export the
// package's handlers, so the chat's server logic auto-updates with `npm update`
// while these one-line files stay put.
//
//   npx telegrade init
//
import { mkdir, writeFile, access } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const VISITOR = ["delete", "history", "init", "react", "read", "send", "stream", "typing", "upload"];
const ADMIN = ["delete", "messages", "react", "read", "send", "stream", "threads", "typing", "upload"];

// app/ lives under src/ in most Next setups; fall back to ./app
const base = existsSync(path.resolve("src/app")) ? "src/app"
  : existsSync(path.resolve("app")) ? "app"
  : "src/app";

const targets = [
  ...VISITOR.map((r) => [`${base}/api/chat/${r}/route.ts`, `telegrade/routes/chat/${r}`]),
  ...ADMIN.map((r) => [`${base}/api/admin/chat/${r}/route.ts`, `telegrade/routes/admin/chat/${r}`]),
  [`${base}/uploads/[...path]/route.ts`, "telegrade/routes/uploads"],
];

let created = 0,
  skipped = 0;
for (const [file, mod] of targets) {
  const abs = path.resolve(file);
  if (await access(abs).then(() => true).catch(() => false)) {
    skipped++;
    continue;
  }
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, `// Auto-generated by \`telegrade init\`. Thin re-export — do not edit.\nexport * from "${mod}";\n`);
  created++;
}

console.log(`\n  telegrade: ${created} route file(s) created, ${skipped} already existed (${base}/)\n`);
console.log("  Next steps (one-time):");
console.log("   1. Append the models from node_modules/telegrade/prisma/chat.prisma to your");
console.log("      schema.prisma, then: npx prisma migrate dev --name telegrade && npx prisma generate");
console.log("   2. tailwind.config: presets: [require('telegrade/tailwind')]");
console.log("   3. Import the styles once:  import 'telegrade/styles.css'");
console.log("   4. next.config: transpilePackages: ['telegrade']");
console.log("   5. instrumentation.ts: configureChat({ getCurrentUser }) from 'telegrade/server'");
console.log("   6. Mount <ChatWidget/> (public) and <AdminChatProvider/>+<ChatConsole/> (admin)");
console.log("\n  Full guide: https://www.npmjs.com/package/telegrade\n");
